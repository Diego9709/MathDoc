// The goal file format `mdc-goal-file/1` (docs/mathdoc.md §4.11, decisions G1–G4): `mdc pull`
// renders a goal draft into a Lean file; `mdc prove` / `mdc split` turn the edited file into a
// `submit` command. The body is scanned by the server's own scanner (lean-source.ts), so a
// file mdc refuses is one the server would refuse, with the same reason where both apply.
import { createHash } from "node:crypto";
import {
  DEFINITION_KINDS,
  mask,
  placeholder,
  scan,
  type Decl,
} from "../lean-source.js";
import type { GoalDraft } from "../goal-draft.js";
import { MdcError } from "./client.js";

export const FORMAT = "mdc-goal-file/1";
export const SEPARATOR = "-- mdc: edit below this line";

export const sha256 = (text: string) =>
  createHash("sha256").update(text, "utf8").digest("hex");
const collapse = (text: string) => text.replace(/\s+/g, " ").trim();
/** A theorem's signature as compared by rule 5: `binders : type`, whitespace collapsed. */
export const signature = (d: { binders?: string; type?: string }) =>
  collapse(`${d.binders ?? ""} : ${d.type ?? ""}`);

/** What `.mdc/` keeps about a pulled file, for turning it back into a request. */
export interface Rendered {
  text: string;
  prefix_sha256: string;
  root: string;
  root_signature: string;
  premises: { name: string; goal: string }[];
  /** Definition IDs of the prefix, dependencies first; sent as the request's `definitions`. */
  definitions: string[];
}

/** Lean option values as LeanGround renders them into `set_option` lines. */
function optionLine(key: string, value: unknown) {
  const v =
    typeof value === "boolean" ? (value ? "true" : "false") : String(value);
  return `set_option ${key} ${v}`;
}

/**
 * The file for a goal draft. The prefix follows the order of LeanGround's checking header
 * (Tools/VerifyWorker.lean at 3965273): raw context, options, universes, opens, registered
 * definitions, notation, attributes, variables. So the file elaborates as the server checks it.
 */
export function render(d: GoalDraft): Rendered {
  const ctx = d.context as Record<string, string[] | undefined>;
  const lines = (key: string, prefix = "") =>
    (ctx[key] ?? []).map((x) => `${prefix}${x}\n`).join("");
  const taken = new Set(d.definitions.map((x) => x.name));
  // Names must be unique and free of `'`; the conclusion keeps its name when it can.
  const fresh = (name: string, suffix: string) => {
    let out = name.replaceAll("'", "_");
    for (let n = 1; taken.has(out); n++)
      out = `${name.replaceAll("'", "_")}${suffix}${n > 1 ? n : ""}`;
    taken.add(out);
    return out;
  };
  const root = fresh(d.root.name, "_goal");
  const premises = d.premises.map((p) => ({
    ...p,
    name: fresh(p.name, "_premise"),
  }));
  let prefix =
    `-- ${FORMAT}\n` +
    `-- project: ${d.project}\n` +
    `-- goal: ${d.goal}\n` +
    `-- root: ${root}\n` +
    `-- Generated by mdc. Do not edit above the "edit below" line; mdc refuses to submit if it changed.\n` +
    `import ${d.root_module}\n` +
    lines("raw") +
    lines("local_options") +
    Object.keys(d.options)
      .sort()
      .map((k) => `${optionLine(k, d.options[k])}\n`)
      .join("") +
    lines("universes", "universe ") +
    lines("opens", "open ");
  for (const def of d.definitions) {
    const source = def.source.endsWith("\n") ? def.source : `${def.source}\n`;
    prefix += `\n-- definition ${def.name} (${def.id.slice(0, 8)})\n${source}`;
  }
  prefix +=
    (d.definitions.length ? "\n" : "") +
    lines("local_notation") +
    lines("local_attrs") +
    lines("variables", "variable ");
  if (d.notes.length)
    prefix +=
      "-- notes (snapshot at pull time, newest first)\n" +
      d.notes
        .map(
          (n) => `-- [${n.at} ${n.actor}] ${collapse(n.text).slice(0, 500)}\n`,
        )
        .join("");
  prefix += `${SEPARATOR}\n`;
  if (prefix.split("\n").filter((l) => l === SEPARATOR).length !== 1)
    throw new MdcError(
      "separator_in_source",
      "a definition contains the separator line",
    );
  const body =
    (premises.length
      ? "\n-- Available premises (existing goals). Unreferenced ones are dropped on submit.\n" +
        premises.map((p) => placeholder(p)).join("")
      : "") +
    "\n-- Goal. Do not change its statement.\n" +
    `theorem ${root}${d.root.binders ? ` ${d.root.binders}` : ""} : ${d.root.type} := by\n  sorry\n`;
  return {
    text: prefix + body,
    prefix_sha256: sha256(prefix),
    root,
    root_signature: signature(d.root),
    premises: premises.map((p) => ({ name: p.name, goal: p.goal })),
    definitions: d.definitions.map((x) => x.id),
  };
}

export interface Parsed {
  mode: "leaf" | "sketch";
  component: "lean-worker" | "lean-worker-sketch";
  /** The body as submitted: pulled premises it does not use are removed (G1). */
  source: string;
  placeholders: string[];
  dropped: string[];
  new_definitions: string[];
  root_is_sorry: boolean;
}

const IDENT = "[\\p{L}\\p{N}_'!?]";
/**
 * Whether `name` occurs as an identifier in `text` (comments and strings already masked).
 * `h.name` and `name.symm` count: a wrong "used" only keeps a premise, which the server then
 * refuses as `subgoal_unused`, while a wrong "unused" would break the proof.
 */
export function mentions(text: string, name: string) {
  const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp(`(?<!${IDENT})${escaped}(?!${IDENT})`, "u").test(text);
}

/** §4.11 steps 1–6: check a goal file against its record and derive the submission. */
export function parse(
  raw: string,
  record: {
    root: string;
    root_signature: string;
    prefix_sha256: string;
    premises: { name: string }[];
  },
): Parsed {
  let text = raw.replace(/\r\n/g, "\n");
  if (!text.endsWith("\n")) text += "\n";
  const lines = text.split("\n");
  if (lines[0] !== `-- ${FORMAT}`)
    throw new MdcError(
      "unsupported_format",
      `the first line must be "-- ${FORMAT}"`,
    );
  const separators = lines.filter((l) => l === SEPARATOR).length;
  if (separators === 0)
    throw new MdcError("separator_missing", `no line "${SEPARATOR}"`);
  if (separators > 1)
    throw new MdcError(
      "separator_duplicated",
      `the line "${SEPARATOR}" appears ${separators} times`,
    );
  const cut = text.indexOf(`\n${SEPARATOR}\n`) + SEPARATOR.length + 2;
  const prefix = text.slice(0, cut);
  const body = text.slice(cut);
  if (sha256(prefix) !== record.prefix_sha256)
    throw new MdcError(
      "prefix_modified",
      "the part above the separator changed since mdc pull",
    );

  const s = scan(body);
  if (s.prelude.length) {
    const p = s.prelude[0];
    throw new MdcError(
      "context_in_body",
      `${collapse(body.slice(p.start, p.end))}: import and context commands belong to the project environment`,
    );
  }
  if (s.rejection) throw new MdcError(s.rejection.reason, s.rejection.details);
  const theorem = (d: Decl) => d.kind === "theorem" || d.kind === "lemma";
  const roots = s.decls.filter((d) => d.name === record.root);
  if (!roots.length || !theorem(roots[0]))
    throw new MdcError(
      "root_missing",
      `no theorem ${record.root} below the separator`,
    );
  if (roots.length > 1)
    throw new MdcError(
      "root_duplicated",
      `${record.root} is declared ${roots.length} times`,
    );
  const names = [
    ...scan(prefix).decls.map((d) => d.name),
    ...s.decls.map((d) => d.name),
  ];
  const quoted = names.find((n) => n.includes("'"));
  if (quoted)
    throw new MdcError("invalid_name", `${quoted}: names may not contain '`);
  const dup = names.find((n, i) => names.indexOf(n) !== i);
  if (dup) throw new MdcError("duplicate_name", `${dup} is declared twice`);
  const root = roots[0];
  if (signature(root) !== record.root_signature)
    throw new MdcError(
      "root_statement_changed",
      `${record.root} must keep the signature ${record.root_signature}`,
    );
  let placeholders = s.decls.filter((d) => d !== root && theorem(d) && d.sorry);
  const same = placeholders.find((d) => signature(d) === record.root_signature);
  if (same)
    throw new MdcError(
      "premise_equals_root",
      `the premise ${same.name} states the goal itself`,
    );

  // G1: pulled premises that nothing else mentions are dropped.
  const masked = mask(body);
  const pulled = new Set(record.premises.map((p) => p.name));
  const dropped = placeholders.filter((d) => {
    if (!pulled.has(d.name)) return false;
    const rest =
      masked.slice(0, d.start) +
      " ".repeat(d.end - d.start) +
      masked.slice(d.end);
    return !mentions(rest, d.name);
  });
  placeholders = placeholders.filter((d) => !dropped.includes(d));
  // A declaration ends at its last non-blank line; comments after it stay.
  const extent = (d: Decl) => {
    const text = masked.slice(d.start, d.end).trimEnd();
    const newline = body.indexOf("\n", d.start + text.length);
    return newline < 0 ? d.end : Math.min(newline + 1, d.end);
  };
  let source = "";
  let at = 0;
  for (const d of dropped) {
    source += body.slice(at, d.start);
    at = extent(d);
  }
  source += body.slice(at);

  // New definitions: those the premise statements mention, and what they mention in turn.
  const definitions = s.decls.filter((d) => DEFINITION_KINDS.includes(d.kind));
  const needed = new Set<Decl>();
  let frontier = placeholders.map((d) => signature(d));
  while (frontier.length) {
    const next: string[] = [];
    for (const d of definitions)
      if (!needed.has(d) && frontier.some((t) => mentions(t, d.name))) {
        needed.add(d);
        next.push(masked.slice(d.start, d.end));
      }
    frontier = next;
  }
  const sketch = placeholders.length > 0;
  return {
    mode: sketch ? "sketch" : "leaf",
    component: sketch ? "lean-worker-sketch" : "lean-worker",
    source,
    placeholders: placeholders.map((d) => d.name),
    dropped: dropped.map((d) => d.name),
    new_definitions: definitions
      .filter((d) => needed.has(d))
      .map((d) => d.name),
    root_is_sorry: Boolean(root.sorry),
  };
}
